// Generates the spike-authored fixture fonts into the quarantine incoming folder, next to the
// operator-downloaded families. Their bytes depend only on this code and the committed fixtures.
import { readdirSync, readFileSync } from "node:fs";
import { writeAtomic } from "../paths.js";
import { buildFixtureFont } from "./fixture-font.js";
import { incomingDir } from "./fonts.js";
import { JA_SAMPLE_SET, LATIN_SAMPLE_SET } from "./samples.js";

export const FIXTURE_LICENSE = `Fixture fonts generated by spikes/film/src/fonts/fixture-font.ts.
Dedicated to the public domain under CC0-1.0. Redistribution and embedding in video are permitted.
`;

function range(from: number, to: number): number[] {
  return Array.from({ length: to - from + 1 }, (_, i) => from + i);
}

function strings(value: unknown, out: string[]): string[] {
  if (typeof value === "string") out.push(value);
  else if (Array.isArray(value)) value.forEach((v) => strings(v, out));
  else if (value && typeof value === "object") Object.values(value).forEach((v) => strings(v, out));
  return out;
}

/** Every character used in the committed project fixtures (captions, titles, worldview). */
export function projectFixtureChars(fixturesDir: string): number[] {
  const dir = `${fixturesDir}project/`;
  const texts: string[] = [];
  for (const entry of readdirSync(dir, { recursive: true, withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".json")) strings(JSON.parse(readFileSync(`${entry.parentPath}/${entry.name}`, "utf8")), texts);
  }
  return [...new Set(texts.join("").split("").map((c) => c.codePointAt(0)!))];
}

const LATIN = [...range(0x20, 0x7e), 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026];

export function writeFixtureFonts(state: string, fixturesDir: string): string[] {
  const japanese = [
    ...LATIN,
    ...range(0x3000, 0x303f),
    ...range(0x3041, 0x30ff),
    ...range(0xff01, 0xff5e),
    ...JA_SAMPLE_SET.map((c) => c.codePointAt(0)!),
    ...projectFixtureChars(fixturesDir),
  ];
  const latinOnly = [...LATIN, ...LATIN_SAMPLE_SET.map((c) => c.codePointAt(0)!)];
  const fonts = [
    { dir: "fixture-sans-jp", file: "FixtureSansJP-Regular.ttf", family: "Fixture Sans JP", ps: "FixtureSansJP-Regular", codepoints: japanese, advance: 1000 },
    { dir: "fixture-serif-jp", file: "FixtureSerifJP-Regular.ttf", family: "Fixture Serif JP", ps: "FixtureSerifJP-Regular", codepoints: japanese, advance: 1000 },
    { dir: "fixture-latin", file: "FixtureLatin-Regular.ttf", family: "Fixture Latin", ps: "FixtureLatin-Regular", codepoints: latinOnly, advance: 600 },
  ];
  for (const f of fonts) {
    const target = incomingDir(state, f.dir);
    writeAtomic(`${target}${f.file}`, buildFixtureFont({ family: f.family, postscriptName: f.ps, codepoints: f.codepoints, advance: f.advance, weight: 400 }));
    writeAtomic(`${target}LICENSE.txt`, FIXTURE_LICENSE);
  }
  // A negative candidate: the Latin font cut off partway through its tables.
  const latin = buildFixtureFont({ family: "Fixture Truncated", postscriptName: "FixtureTruncated-Regular", codepoints: latinOnly, advance: 600, weight: 400 });
  writeAtomic(`${incomingDir(state, "fixture-truncated")}FixtureTruncated-Regular.ttf`, latin.slice(0, Math.floor(latin.length * 0.6)));
  writeAtomic(`${incomingDir(state, "fixture-truncated")}LICENSE.txt`, FIXTURE_LICENSE);
  return [...fonts.map((f) => f.dir), "fixture-truncated"];
}
